-- Crea la solicitud y su primer mensaje de una vez (una solicitud sin mensaje
-- no sirve). SECURITY INVOKER: pasan las politicas y los triggers de arriba.
CREATE OR REPLACE FUNCTION public.create_support_ticket(
  p_type text,
  p_subject text,
  p_body text,
  p_business_id uuid DEFAULT NULL
)
RETURNS bigint
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
DECLARE
  v_id bigint;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'not_authenticated' USING ERRCODE = '42501';
  END IF;
  INSERT INTO public.support_tickets (user_id, type, subject, business_id)
  VALUES (auth.uid(), COALESCE(NULLIF(btrim(p_type), ''), 'question'), p_subject, p_business_id)
  RETURNING id INTO v_id;
  INSERT INTO public.support_ticket_messages (ticket_id, author_id, body)
  VALUES (v_id, auth.uid(), p_body);
  RETURN v_id;
END;
$$;

-- Cambio de estado. Admin: cualquiera. Usuario, en la suya: cerrarla (desde
-- cualquier estado) o reabrirla (desde resolved/closed).
CREATE OR REPLACE FUNCTION public.support_ticket_set_status(p_ticket_id bigint, p_status text)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_owner  uuid;
  v_status text;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'not_authenticated' USING ERRCODE = '42501';
  END IF;
  IF p_status NOT IN ('open', 'in_progress', 'waiting_user', 'resolved', 'closed') THEN
    RAISE EXCEPTION 'support_ticket_bad_status' USING ERRCODE = '22023';
  END IF;

  SELECT user_id, status INTO v_owner, v_status
  FROM public.support_tickets WHERE id = p_ticket_id
  FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'support_ticket_not_found' USING ERRCODE = 'P0002';
  END IF;

  IF NOT public.opynio_is_admin() THEN
    IF v_owner IS DISTINCT FROM auth.uid() THEN
      RAISE EXCEPTION 'support_ticket_not_found' USING ERRCODE = 'P0002';
    END IF;
    IF NOT (p_status = 'closed'
            OR (p_status = 'open' AND v_status IN ('resolved', 'closed'))) THEN
      RAISE EXCEPTION 'support_ticket_forbidden_status' USING ERRCODE = '42501';
    END IF;
  END IF;

  UPDATE public.support_tickets SET status = p_status WHERE id = p_ticket_id;
  RETURN p_status;
END;
$$;

-- Bandeja del admin: filtros, busqueda (asunto, n.º, nombre, usuario, email)
-- y paginacion, con nombre y email del usuario (auth.users solo desde aqui).
CREATE OR REPLACE FUNCTION public.admin_list_support_tickets(
  p_status text DEFAULT NULL,
  p_type text DEFAULT NULL,
  p_search text DEFAULT NULL,
  p_limit int DEFAULT 25,
  p_offset int DEFAULT 0
)
RETURNS TABLE (
  id bigint,
  user_id uuid,
  user_name text,
  user_username text,
  user_email text,
  type text,
  subject text,
  status text,
  business_id uuid,
  business_name text,
  created_at timestamptz,
  updated_at timestamptz,
  last_message_at timestamptz,
  message_count bigint,
  last_is_staff boolean,
  total_count bigint
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_status text := NULLIF(NULLIF(btrim(p_status), ''), 'all');
  v_type   text := NULLIF(NULLIF(btrim(p_type), ''), 'all');
  v_search text := NULLIF(btrim(p_search), '');
  v_num    bigint;
BEGIN
  IF NOT public.opynio_is_admin() THEN
    RAISE EXCEPTION 'Acción solo para administradores.' USING ERRCODE = '42501';
  END IF;
  IF v_search ~ '^#?[0-9]{1,15}$' THEN
    v_num := ltrim(v_search, '#')::bigint;
  END IF;

  RETURN QUERY
  SELECT t.id, t.user_id, p.name, p.username, u.email::text,
         t.type, t.subject, t.status, t.business_id, b.name::text,
         t.created_at, t.updated_at, t.last_message_at,
         (SELECT count(*) FROM public.support_ticket_messages m WHERE m.ticket_id = t.id),
         (SELECT m.is_staff FROM public.support_ticket_messages m
           WHERE m.ticket_id = t.id ORDER BY m.created_at DESC, m.id DESC LIMIT 1),
         count(*) OVER ()
  FROM public.support_tickets t
  LEFT JOIN public.profiles p ON p.id = t.user_id
  LEFT JOIN auth.users u ON u.id = t.user_id
  LEFT JOIN public.businesses b ON b.id = t.business_id
  WHERE (v_status IS NULL
         OR (v_status = 'active' AND t.status IN ('open', 'in_progress', 'waiting_user'))
         OR t.status = v_status)
    AND (v_type IS NULL OR t.type = v_type)
    AND (v_search IS NULL
         OR t.id = v_num
         OR t.subject ILIKE '%' || v_search || '%'
         OR p.name ILIKE '%' || v_search || '%'
         OR p.username ILIKE '%' || v_search || '%'
         OR u.email ILIKE '%' || v_search || '%')
  ORDER BY (t.status = 'open') DESC, t.last_message_at DESC, t.id DESC
  LIMIT LEAST(GREATEST(COALESCE(p_limit, 25), 1), 100)
  OFFSET GREATEST(COALESCE(p_offset, 0), 0);
END;
$$;

-- Contadores por estado (pestañas del admin y tarjeta del panel).
CREATE OR REPLACE FUNCTION public.admin_support_ticket_counts()
RETURNS TABLE (status text, n bigint)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  IF NOT public.opynio_is_admin() THEN
    RAISE EXCEPTION 'Acción solo para administradores.' USING ERRCODE = '42501';
  END IF;
  RETURN QUERY SELECT t.status, count(*) FROM public.support_tickets t GROUP BY t.status;
END;
$$;

