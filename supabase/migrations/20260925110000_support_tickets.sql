-- =============================================================================
-- Solicitudes de soporte (tickets). 2026-09-25
--
-- Hasta ahora «Soporte» solo tenia formularios sueltos (error, reclamar empresa,
-- apelar resena) que mandaban un correo, y la tarjeta «Soporte» del panel de
-- admin estaba en «Proximamente». Esto crea el hilo de conversacion:
--
-- - support_tickets: una fila por solicitud. Tipo cerrado (question, account,
--   billing, business, account_deletion, other) y estado (open, in_progress,
--   waiting_user, resolved, closed).
-- - support_ticket_messages: los mensajes del hilo. `is_staff` lo pone el
--   servidor (trigger), nunca el cliente: true solo si escribe un admin en una
--   solicitud que no es suya.
--
-- Permisos (RLS):
-- - El usuario ve y crea solo lo suyo; responde en sus solicitudes no cerradas.
--   No puede tocar las filas de support_tickets con UPDATE: para cerrar o
--   reabrir la suya usa support_ticket_set_status(), que solo le deja esas dos
--   transiciones. Nadie borra por la API.
-- - El admin (opynio_is_admin(), como las migraciones del 23-24/09) ve todo,
--   responde y cambia cualquier estado (misma funcion).
-- - anon: nada.
--
-- Al responder un admin, un trigger inserta una notificacion en
-- public.notifications (la campana de la cabecera; solo user_id, type y
-- message, las columnas comunes a prod y local) y pasa la solicitud a
-- «waiting_user». Si responde el usuario, vuelve a «open».
--
-- Tambien anade public.notifications a la publicacion supabase_realtime si
-- existe y no estaba (AuthContext ya se suscribe a sus INSERT; con RLS, cada
-- usuario solo recibe los suyos). Si no hay publicacion o no hay permiso, se
-- avisa con NOTICE y se sigue: la notificacion aparece igual al recargar.
--
-- Sin adjuntos (fuera de esta version).
--
-- Vuelta atras:
--   DROP FUNCTION IF EXISTS public.admin_list_support_tickets(text, text, text, int, int);
--   DROP FUNCTION IF EXISTS public.admin_support_ticket_counts();
--   DROP FUNCTION IF EXISTS public.support_ticket_set_status(bigint, text);
--   DROP FUNCTION IF EXISTS public.create_support_ticket(text, text, text, uuid);
--   DROP TABLE IF EXISTS public.support_ticket_messages;
--   DROP TABLE IF EXISTS public.support_tickets;
--   DROP FUNCTION IF EXISTS public.support_tickets_before_write();
--   DROP FUNCTION IF EXISTS public.support_messages_before_insert();
--   DROP FUNCTION IF EXISTS public.support_messages_after_insert();
--   (la publicacion de notifications se puede dejar: no depende de esto)
-- =============================================================================
BEGIN;

-- ---------------------------------------------------------------------------
-- Tablas
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.support_tickets (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id         uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  type            text NOT NULL DEFAULT 'question'
                  CHECK (type IN ('question', 'account', 'billing', 'business', 'account_deletion', 'other')),
  subject         text NOT NULL
                  CHECK (char_length(btrim(subject)) BETWEEN 3 AND 150),
  status          text NOT NULL DEFAULT 'open'
                  CHECK (status IN ('open', 'in_progress', 'waiting_user', 'resolved', 'closed')),
  business_id     uuid REFERENCES public.businesses(id) ON DELETE SET NULL,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  last_message_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.support_ticket_messages (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id  bigint NOT NULL REFERENCES public.support_tickets(id) ON DELETE CASCADE,
  author_id  uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  is_staff   boolean NOT NULL DEFAULT false,
  body       text NOT NULL
             CHECK (char_length(btrim(body)) BETWEEN 1 AND 5000),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_support_tickets_user_last
  ON public.support_tickets (user_id, last_message_at DESC);
CREATE INDEX IF NOT EXISTS idx_support_tickets_status_last
  ON public.support_tickets (status, last_message_at DESC);
CREATE INDEX IF NOT EXISTS idx_support_messages_ticket_created
  ON public.support_ticket_messages (ticket_id, created_at);
CREATE INDEX IF NOT EXISTS idx_support_messages_author_created
  ON public.support_ticket_messages (author_id, created_at DESC);

ALTER TABLE public.support_tickets ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.support_ticket_messages ENABLE ROW LEVEL SECURITY;

-- En prod `postgres` concede todo a anon/authenticated en public por defecto.
REVOKE ALL ON TABLE public.support_tickets FROM anon, authenticated, public;
REVOKE ALL ON TABLE public.support_ticket_messages FROM anon, authenticated, public;
GRANT SELECT, INSERT ON TABLE public.support_tickets TO authenticated;
GRANT SELECT, INSERT ON TABLE public.support_ticket_messages TO authenticated;
GRANT ALL ON TABLE public.support_tickets TO service_role;
GRANT ALL ON TABLE public.support_ticket_messages TO service_role;

-- ---------------------------------------------------------------------------
-- Politicas
-- ---------------------------------------------------------------------------
DROP POLICY IF EXISTS "support_tickets_select_own_or_admin" ON public.support_tickets;
CREATE POLICY "support_tickets_select_own_or_admin"
  ON public.support_tickets FOR SELECT TO authenticated
  USING (user_id = auth.uid() OR public.opynio_is_admin());

DROP POLICY IF EXISTS "support_tickets_insert_own" ON public.support_tickets;
CREATE POLICY "support_tickets_insert_own"
  ON public.support_tickets FOR INSERT TO authenticated
  WITH CHECK (user_id = auth.uid());

DROP POLICY IF EXISTS "support_messages_select_own_or_admin" ON public.support_ticket_messages;
CREATE POLICY "support_messages_select_own_or_admin"
  ON public.support_ticket_messages FOR SELECT TO authenticated
  USING (
    public.opynio_is_admin()
    OR EXISTS (SELECT 1 FROM public.support_tickets t
               WHERE t.id = ticket_id AND t.user_id = auth.uid())
  );

DROP POLICY IF EXISTS "support_messages_insert_own_or_admin" ON public.support_ticket_messages;
CREATE POLICY "support_messages_insert_own_or_admin"
  ON public.support_ticket_messages FOR INSERT TO authenticated
  WITH CHECK (
    author_id = auth.uid()
    AND (
      public.opynio_is_admin()
      OR EXISTS (SELECT 1 FROM public.support_tickets t
                 WHERE t.id = ticket_id AND t.user_id = auth.uid() AND t.status <> 'closed')
    )
  );

