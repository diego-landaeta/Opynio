-- Solicitudes: al crear, estado y fechas los pone el servidor, la empresa (si
-- la hay) tiene que ser del usuario y hay tope de 5 por hora (no admin). Al
-- actualizar (solo desde las funciones de abajo), user_id y created_at no se
-- mueven.
CREATE OR REPLACE FUNCTION public.support_tickets_before_write()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
DECLARE
  v_recent int;
BEGIN
  IF TG_OP = 'INSERT' THEN
    NEW.subject := btrim(NEW.subject);
    NEW.created_at := now();
    NEW.updated_at := now();
    NEW.last_message_at := now();
    IF auth.uid() IS NOT NULL AND NOT public.opynio_is_admin() THEN
      NEW.status := 'open';
      IF NEW.business_id IS NOT NULL
         AND NOT public.user_owns_business(NEW.business_id::text) THEN
        RAISE EXCEPTION 'support_ticket_business_not_owned' USING ERRCODE = '42501';
      END IF;
      SELECT count(*) INTO v_recent
      FROM public.support_tickets
      WHERE user_id = NEW.user_id AND created_at > now() - interval '1 hour';
      IF v_recent >= 5 THEN
        RAISE EXCEPTION 'support_ticket_rate_limited' USING ERRCODE = 'P0001';
      END IF;
    END IF;
  ELSE
    NEW.id := OLD.id;
    NEW.user_id := OLD.user_id;
    NEW.created_at := OLD.created_at;
    NEW.updated_at := now();
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_support_tickets_before_write ON public.support_tickets;
CREATE TRIGGER trg_support_tickets_before_write
  BEFORE INSERT OR UPDATE ON public.support_tickets
  FOR EACH ROW EXECUTE FUNCTION public.support_tickets_before_write();

-- Mensajes: autor, fecha e is_staff los decide el servidor. Tope de 30
-- mensajes por hora para quien no es admin.
CREATE OR REPLACE FUNCTION public.support_messages_before_insert()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_owner  uuid;
  v_recent int;
BEGIN
  SELECT user_id INTO v_owner FROM public.support_tickets WHERE id = NEW.ticket_id;
  NEW.body := btrim(NEW.body);
  NEW.created_at := now();
  IF auth.uid() IS NOT NULL THEN
    NEW.author_id := auth.uid();
    NEW.is_staff := public.opynio_is_admin() AND v_owner IS DISTINCT FROM auth.uid();
    IF NOT NEW.is_staff THEN
      SELECT count(*) INTO v_recent
      FROM public.support_ticket_messages
      WHERE author_id = auth.uid() AND created_at > now() - interval '1 hour';
      IF v_recent >= 30 THEN
        RAISE EXCEPTION 'support_message_rate_limited' USING ERRCODE = 'P0001';
      END IF;
    END IF;
  END IF;
  -- Sin sesion (service_role / SQL): se respeta lo que venga.
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_support_messages_before_insert ON public.support_ticket_messages;
CREATE TRIGGER trg_support_messages_before_insert
  BEFORE INSERT ON public.support_ticket_messages
  FOR EACH ROW EXECUTE FUNCTION public.support_messages_before_insert();

-- Tras un mensaje: fecha del ultimo mensaje y estado; si es de soporte, aviso
-- en la web al usuario. SECURITY DEFINER: el usuario no tiene UPDATE sobre la
-- solicitud ni INSERT sobre notificaciones ajenas.
CREATE OR REPLACE FUNCTION public.support_messages_after_insert()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_ticket public.support_tickets%ROWTYPE;
BEGIN
  SELECT * INTO v_ticket FROM public.support_tickets WHERE id = NEW.ticket_id;
  IF NOT FOUND THEN
    RETURN NEW;
  END IF;

  UPDATE public.support_tickets
     SET last_message_at = NEW.created_at,
         status = CASE
           WHEN NEW.is_staff AND status IN ('open', 'in_progress') THEN 'waiting_user'
           WHEN NOT NEW.is_staff AND status IN ('waiting_user', 'resolved') THEN 'open'
           ELSE status
         END
   WHERE id = NEW.ticket_id;

  IF NEW.is_staff THEN
    INSERT INTO public.notifications (user_id, type, message)
    VALUES (v_ticket.user_id, 'support_reply', left(v_ticket.subject, 150));
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_support_messages_after_insert ON public.support_ticket_messages;
CREATE TRIGGER trg_support_messages_after_insert
  AFTER INSERT ON public.support_ticket_messages
  FOR EACH ROW EXECUTE FUNCTION public.support_messages_after_insert();

